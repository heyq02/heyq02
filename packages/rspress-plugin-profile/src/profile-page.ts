import { documentTitleSuffix, formatCount } from '@heyq02/rspress-site-content'
import type { Intro } from '@heyq02/rspress-site-content'

import type { ContributionCalendar } from './github-contributions.ts'
import type { PinnedProject } from './github-pinned.ts'

export interface ProfileProjectView {
  name: string
  href: string
  summary: string
  language: string
  stars: string
  forks: string
}

export interface ProfilePageView {
  name: string
  tags: string[]
  avatar: string
  sections: Intro['sections']
  projects: ProfileProjectView[]
  contributions: ContributionCalendar
}

export function profilePage(
  intro: Intro,
  projects: PinnedProject[] = [],
  contributions: ContributionCalendar = { total: 0, href: '', weeks: [] }
): ProfilePageView {
  return {
    name: intro.name,
    tags: intro.tags,
    avatar: intro.avatar,
    sections: intro.sections,
    projects: projects.map(project => ({
      name: project.name,
      href: project.href,
      summary: intro.projectSummaries[project.name] ?? project.summary,
      language: project.language,
      stars: formatCount(project.stars),
      forks: formatCount(project.forks)
    })),
    contributions
  }
}

function yamlString(value: string): string {
  return JSON.stringify(value)
}

/** Thin MDX shell — body UI lives in `@theme/ProfilePage`. */
export function renderHomeMdx(
  intro: Intro,
  pinned: PinnedProject[] = [],
  contributions?: ContributionCalendar
): string {
  const page = profilePage(intro, pinned, contributions)
  return `---
pageType: doc-wide
title: ${yamlString(page.name)}
titleSuffix: ${yamlString(documentTitleSuffix(intro))}
sidebar: false
outline: false
footer: false
---

import { ProfilePage } from '@theme/ProfilePage'

<ProfilePage />
`
}

/** Generated module consumed by `@theme/ProfilePage`. */
export function renderProfileDataModule(
  page: Pick<ProfilePageView, 'projects' | 'contributions'>
): string {
  return `/** Generated by @heyq02/rspress-plugin-profile — do not edit. */

export interface ProfileProject {
  name: string
  href: string
  summary: string
  language: string
  stars: string
  forks: string
}

export type ContributionLevel = 0 | 1 | 2 | 3 | 4

export interface ContributionDay {
  date: string
  count: number
  level: ContributionLevel
}

export interface ContributionCalendar {
  total: number
  href: string
  weeks: ContributionDay[][]
}

export const pinnedProjects: ProfileProject[] = ${JSON.stringify(page.projects, null, 2)}

export const contributionCalendar: ContributionCalendar = ${JSON.stringify(page.contributions, null, 2)}
`
}
