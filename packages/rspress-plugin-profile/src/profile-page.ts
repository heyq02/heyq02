import { formatCount } from '@heyq02/rspress-site-content'
import type { Intro } from '@heyq02/rspress-site-content'

import type { PinnedProject } from './github-pinned.ts'
import { skillIconsPicture } from './skills-picture.ts'

export interface ProfileProjectView {
  name: string
  href: string
  summary: string
  language: string
  stars: string
  forks: string
}

export interface ProfileSkillsPicture {
  alt: string
  src: string
}

export interface ProfilePageView {
  name: string
  tags: string[]
  avatar: string
  sections: Intro['sections']
  education: Intro['education']
  experiences: Intro['experiences']
  skills: ProfileSkillsPicture
  projects: ProfileProjectView[]
}

export function profilePage(intro: Intro, projects: PinnedProject[] = []): ProfilePageView {
  return {
    name: intro.name,
    tags: intro.tags,
    avatar: intro.avatar,
    sections: intro.sections,
    education: intro.education,
    experiences: intro.experiences,
    skills: skillIconsPicture(intro.skills),
    projects: projects.map(project => ({
      name: project.name,
      href: project.href,
      summary: project.summary,
      language: project.language,
      stars: formatCount(project.stars),
      forks: formatCount(project.forks)
    }))
  }
}

/** Browser tab suffix after the name (`永琪 - …`). */
export function documentTitleSuffix(
  intro: Intro,
  page: Pick<ProfilePageView, 'tags'> = profilePage(intro)
): string {
  return `${[...page.tags, intro.bio].join('，')}。`
}

function yamlString(value: string): string {
  return JSON.stringify(value)
}

/** Thin MDX shell — body UI lives in `@theme/ProfilePage`. */
export function renderHomeMdx(intro: Intro, pinned: PinnedProject[] = []): string {
  const page = profilePage(intro, pinned)
  return `---
pageType: doc-wide
title: ${yamlString(page.name)}
titleSuffix: ${yamlString(documentTitleSuffix(intro, page))}
sidebar: false
outline: false
footer: false
---

import { ProfilePage } from '@theme/ProfilePage'

<ProfilePage />
`
}

/** Generated module consumed by `@theme/ProfilePage`. */
export function renderProfileDataModule(
  page: Pick<ProfilePageView, 'projects' | 'skills'>
): string {
  return `/** Generated by @heyq02/rspress-plugin-profile — do not edit. */

export interface ProfileProject {
  name: string
  href: string
  summary: string
  language: string
  stars: string
  forks: string
}

export interface ProfileSkillsPicture {
  alt: string
  src: string
}

export const pinnedProjects: ProfileProject[] = ${JSON.stringify(page.projects, null, 2)}

export const skillsPicture: ProfileSkillsPicture = ${JSON.stringify(page.skills, null, 2)}
`
}
