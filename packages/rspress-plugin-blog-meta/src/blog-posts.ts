import { readdir, readFile } from 'node:fs/promises'
import { basename, resolve } from 'node:path'

export interface BlogPost {
  slug: string
  href: string
  title: string
  description: string
  date: string
}

function parseFrontmatter(raw: string): { data: Record<string, string>; body: string } {
  if (!raw.startsWith('---\n')) {
    return { data: {}, body: raw }
  }
  const end = raw.indexOf('\n---\n', 4)
  if (end === -1) {
    return { data: {}, body: raw }
  }
  const data: Record<string, string> = {}
  for (const line of raw.slice(4, end).split('\n')) {
    const match = /^(?<key>[A-Za-z][\w-]*)\s*:\s*(?<value>.*)$/.exec(line)
    if (!match?.groups) {
      continue
    }
    data[match.groups.key] = match.groups.value.replaceAll(/^["']|["']$/g, '').trim()
  }
  return { data, body: raw.slice(end + 5) }
}

function titleFromBody(body: string) {
  const heading = /^#\s+(.+)$/m.exec(body)?.[1] ?? ''
  return heading
    .replace(/^[\p{Extended_Pictographic}\p{Emoji_Presentation}\uFE0F\u200D\s]+/u, '')
    .trim()
}

/** Prefer frontmatter date; otherwise pull YYYY-MM-DD from the slug/filename. */
export function dateFromSlug(slug: string): string {
  return /\d{4}-\d{2}-\d{2}/.exec(slug)?.[0] ?? ''
}

async function listMarkdownEntries(dir: string, hrefPrefix: string): Promise<BlogPost[]> {
  let files: string[]
  try {
    files = await readdir(dir)
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
      return []
    }
    throw error
  }

  const posts: BlogPost[] = []
  for (const file of files) {
    if (!/\.mdx?$/.test(file) || file === 'index.md' || file === 'index.mdx') {
      continue
    }
    const raw = await readFile(resolve(dir, file), 'utf8')
    const { data, body } = parseFrontmatter(raw)
    const slug = basename(file).replace(/\.mdx?$/, '')
    posts.push({
      slug,
      href: `${hrefPrefix}${slug}/`,
      title: data.title || titleFromBody(body) || slug,
      description: data.description || summaryFromBody(body),
      date: data.date || dateFromSlug(slug)
    })
  }
  return posts.toSorted(
    (a, b) => (b.date || '').localeCompare(a.date || '') || a.title.localeCompare(b.title)
  )
}

/** First readable paragraph as a short card blurb when frontmatter has no description. */
function summaryFromBody(body: string): string {
  for (const block of body.split(/\n{2,}/)) {
    const raw = block.trim()
    if (
      !raw ||
      raw.startsWith('#') ||
      raw.startsWith('|') ||
      raw.startsWith('- ') ||
      raw.startsWith('```') ||
      /^\d+\./.test(raw)
    ) {
      continue
    }
    const line = raw
      .replaceAll(/\[([^\]]+)\]\([^)]+\)/g, '$1')
      .replaceAll(/[*_`]/g, '')
      .replaceAll(/\s+/g, ' ')
      .trim()
    if (!line) {
      continue
    }
    return line.length > 140 ? `${line.slice(0, 139)}…` : line
  }
  return ''
}

/** `2026-06-22` → `2026年6月22日`. */
export function formatZhDate(iso: string): string {
  const match = /^(?<y>\d{4})-(?<m>\d{2})-(?<d>\d{2})$/.exec(iso)
  if (!match?.groups) {
    return iso
  }
  return `${match.groups.y}年${Number(match.groups.m)}月${Number(match.groups.d)}日`
}

/** TypeScript module of the newest posts for the homepage. */
export function renderRecentPostsModule(posts: BlogPost[], limit = 6): string {
  const recent = posts.slice(0, limit)
  return `/** Generated by @heyq02/rspress-plugin-blog-meta — do not edit. */

export interface RecentPost {
  slug: string
  href: string
  title: string
  description: string
  date: string
}

export const recentPosts: RecentPost[] = ${JSON.stringify(recent, null, 2)}
`
}

/** `/blog/posts/` sidebar entries (newest first). */
export async function listBlogPosts(postsDir: string): Promise<BlogPost[]> {
  return listMarkdownEntries(postsDir, '/blog/posts/')
}

/** `/blog/interview/` sidebar entries (newest first). */
export async function listInterviewNotes(interviewDir: string): Promise<BlogPost[]> {
  return listMarkdownEntries(interviewDir, '/blog/interview/')
}

/** Sidebar labels for the `/blog/` overview page. */
export const BLOG_LABELS = {
  overview: '概览',
  posts: '文章',
  interview: '面经'
} as const

/** Sidebar meta for `/blog/`: 概览, then 文章, then 面经. */
export function renderBlogMetaJson(): string {
  return `${JSON.stringify(
    [
      { type: 'file', name: 'index', label: BLOG_LABELS.overview },
      { type: 'dir', name: 'posts', label: BLOG_LABELS.posts },
      { type: 'dir', name: 'interview', label: BLOG_LABELS.interview }
    ],
    null,
    2
  )}\n`
}

/** Sidebar meta for a blog subsection: one entry per markdown file. */
export function renderPostsMetaJson(posts: BlogPost[]): string {
  return `${JSON.stringify(
    posts.map(post => ({
      type: 'file',
      name: post.slug,
      label: post.title,
      overviewHeaders: [2]
    })),
    null,
    2
  )}\n`
}
